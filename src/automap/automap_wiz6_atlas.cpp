// The tile sheet, exactly as the original authored it: 0x00RRGGBB per pixel,
// row-major, no alpha. Transcribed verbatim from `am_wiz6_res.cpp`.
//
// Two things about these values are not what they look like, both covered in
// PORTING.md:
//
//   - The original declared this `unsigned long`, which is four bytes on
//     Windows but eight on Linux, so half of it would have uploaded as zero
//     here (section 7.1). uint32_t is what it always meant.
//   - The original uploads these bytes as GL_RGBA on a little-endian machine,
//     which exchanges red and blue on screen (section 7.4). The values below
//     are the authored ones; the swap belongs to the surface format, not to
//     the data, and lives in one place in automap_wiz6_atlas.cpp.
//
// So a colour here reads "wrong" against the original's own comments: the
// doors below are authored blue and every player of the mod saw them orange.

